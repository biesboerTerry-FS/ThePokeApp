import Constants from 'expo-constants';
import seedPokemon from '../data/pokemonSeed.json';

function normalizeBaseUrl(value) {
  return String(value || '').replace(/\/+$/, '');
}

function getDevMachineHost() {
  const hostUri =
    Constants.expoConfig?.hostUri ||
    Constants.expoGoConfig?.debuggerHost ||
    Constants.debuggerHost ||
    '';

  if (!hostUri) {
    return '';
  }

  // hostUri can be "192.168.x.x:8087", "http://192.168.x.x:8087", or include a path.
  const withoutScheme = String(hostUri).replace(/^[a-z]+:\/\//i, '');
  const host = withoutScheme.split(':')[0].split('/')[0];
  // Filter out simulator hostnames that won't resolve on a physical device.
  if (host === 'localhost' || host === '127.0.0.1') {
    return '';
  }
  return host;
}

export function getApiBaseUrl() {
  if (process.env.EXPO_PUBLIC_API_BASE_URL) {
    return normalizeBaseUrl(process.env.EXPO_PUBLIC_API_BASE_URL);
  }

  const host = getDevMachineHost();
  if (host) {
    return `http://${host}:8000/api/v1`;
  }

  return 'http://localhost:8000/api/v1';
}

// Offline fallback pool: all 1025 species, generated by scripts/generate-pokemon-seed.mjs
let localPokemonPool = seedPokemon.map((p) => ({ ...p }));

async function requestJson(path, options = {}) {
  const API_BASE_URL = getApiBaseUrl();
  const { headers: optionHeaders, ...restOptions } = options;
  const headers = {
    'Content-Type': 'application/json',
    ...(optionHeaders || {}),
  };

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 5000);

    const response = await fetch(`${API_BASE_URL}${path}`, {
      ...restOptions,
      signal: controller.signal,
      headers,
    });
    clearTimeout(timeoutId);

    if (!response.ok) {
      const text = await response.text();
      throw new Error(text || `Request failed with status ${response.status}`);
    }

    if (response.status === 204) {
      return null;
    }

    return await response.json();
  } catch (error) {
    // Only fall back to local data for network/timeout failures.
    // Re-throw server errors so callers can surface them.
    const isNetworkError =
      error?.name === 'TypeError' ||
      error?.name === 'AbortError' ||
      /network/i.test(error?.message || '');
    if (!isNetworkError) {
      throw error;
    }
    // Return fallback local data when backend server is unreachable
    return handleLocalFallback(path, options);
  }
}

function handleLocalFallback(path, options) {
  const method = (options.method || 'GET').toUpperCase();

  if (path === '/pokemon' && method === 'GET') {
    return [...localPokemonPool];
  }

  if (path.startsWith('/pokemon/') && method === 'GET') {
    const id = path.replace('/pokemon/', '');
    const found = localPokemonPool.find((p) => String(p._id) === String(id));
    if (found) return { ...found };
    throw new Error('Pokémon not found');
  }

  if (path === '/pokemon' && method === 'POST') {
    const payload = JSON.parse(options.body || '{}');
    const newEntry = {
      _id: String(Date.now()),
      name: payload.name || 'New Pokémon',
      types: Array.isArray(payload.types) ? payload.types : ['Normal'],
      level: payload.level || 1,
      sprite: payload.sprite || 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/25.png',
    };
    localPokemonPool = [newEntry, ...localPokemonPool];
    return { ...newEntry };
  }

  if (path.startsWith('/pokemon/') && (method === 'PATCH' || method === 'PUT')) {
    const id = path.replace('/pokemon/', '');
    const payload = JSON.parse(options.body || '{}');
    localPokemonPool = localPokemonPool.map((item) => {
      if (String(item._id) === String(id)) {
        return { ...item, ...payload };
      }
      return item;
    });
    const updated = localPokemonPool.find((item) => String(item._id) === String(id));
    if (!updated) {
      throw new Error('Pokémon not found');
    }
    return { ...updated };
  }

  if (path.startsWith('/pokemon/') && method === 'DELETE') {
    const id = path.replace('/pokemon/', '');
    localPokemonPool = localPokemonPool.filter((item) => String(item._id) !== String(id));
    return null;
  }

  throw new Error(`Unsupported request: ${method} ${path}`);
}

export function getPokemonList() {
  return requestJson('/pokemon');
}

export function getPokemonById(id) {
  return requestJson(`/pokemon/${id}`);
}

export function createPokemon(payload) {
  return requestJson('/pokemon', {
    method: 'POST',
    body: JSON.stringify(payload),
  });
}

export function updatePokemon(id, payload) {
  return requestJson(`/pokemon/${id}`, {
    method: 'PATCH',
    body: JSON.stringify(payload),
  });
}

export function deletePokemon(id) {
  return requestJson(`/pokemon/${id}`, { method: 'DELETE' });
}


