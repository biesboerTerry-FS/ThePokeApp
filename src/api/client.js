import Constants from 'expo-constants';
import AsyncStorage from '@react-native-async-storage/async-storage';
import seedPokemon from '../data/pokemonSeed.json';
import { backendHealthyAtBuild } from './backendStatus.generated';

// The client stores a stable trainer id in the persisted app state. Read it
// so the API can scope Pokédex entries to this trainer (plus shared seed data).
async function getUserId() {
  try {
    const raw = await AsyncStorage.getItem('pokeapp:state:v1');
    if (!raw) return '';
    const parsed = JSON.parse(raw);
    return String(parsed.userId || '').trim();
  } catch (error) {
    return '';
  }
}

function normalizeBaseUrl(value) {
  return String(value || '').replace(/\/+$/, '');
}

function getDevMachineHost() {
  const hostUri =
    Constants.expoConfig?.hostUri ||
    Constants.expoGoConfig?.debuggerHost ||
    Constants.debuggerHost ||
    '';

  if (!hostUri) {
    return '';
  }

  // hostUri can be "192.168.x.x:8087", "http://192.168.x.x:8087", or include a path.
  const withoutScheme = String(hostUri).replace(/^[a-z]+:\/\//i, '');
  const host = withoutScheme.split(':')[0].split('/')[0];
  // Filter out simulator hostnames that won't resolve on a physical device.
  if (host === 'localhost' || host === '127.0.0.1') {
    return '';
  }
  return host;
}

export function getApiBaseUrl() {
  if (process.env.EXPO_PUBLIC_API_BASE_URL) {
    return normalizeBaseUrl(process.env.EXPO_PUBLIC_API_BASE_URL);
  }

  const host = getDevMachineHost();
  if (host) {
    return `http://${host}:8000/api/v1`;
  }

  return 'http://localhost:8000/api/v1';
}

// When the backend was degraded at build time (503 while MongoDB is being
// configured), skip API calls entirely and use the bundled offline data. The
// build-time probe in scripts/check-backend.mjs flips this after MongoDB is
// connected and the frontend is redeployed.
// With no explicit API URL on a deployed host, requests to the default
// localhost:8000 could only fail, so use offline data too.
function shouldUseLocalOnly() {
  if (!backendHealthyAtBuild) {
    return true;
  }
  if (process.env.EXPO_PUBLIC_API_BASE_URL) {
    return false;
  }
  if (typeof window === 'undefined' || !window.location) {
    return false;
  }
  const hostname = window.location.hostname;
  return hostname !== 'localhost' && hostname !== '127.0.0.1';
}

// Offline fallback pool: all 1025 species, generated by scripts/generate-pokemon-seed.mjs
let localPokemonPool = seedPokemon.map((p) => ({ ...p }));

// The backend requires a JWT for writes, but this demo has no login screen.
// Fetch a short-lived demo token once and reuse it for all mutations.
let demoTokenPromise = null;
async function getDemoToken(apiBaseUrl) {
  if (!demoTokenPromise) {
    demoTokenPromise = (async () => {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 5000);
      try {
        const response = await fetch(`${apiBaseUrl}/auth/demo`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          signal: controller.signal,
        });
        if (!response.ok) throw new Error(`Demo auth failed: ${response.status}`);
        const data = await response.json();
        if (!data.token) throw new Error('Demo auth returned no token.');
        return data.token;
      } finally {
        clearTimeout(timeoutId);
      }
    })().catch((error) => {
      demoTokenPromise = null; // retry on the next mutation
      throw error;
    });
  }
  return demoTokenPromise;
}

async function requestJson(path, options = {}) {
  if (shouldUseLocalOnly()) {
    return handleLocalFallback(path, options);
  }

  const API_BASE_URL = getApiBaseUrl();
  const { headers: optionHeaders, ...restOptions } = options;
  const headers = {
    'Content-Type': 'application/json',
    ...(optionHeaders || {}),
  };

  // Reads stay public. Authenticate mutations with the demo token so the
  // "Add Pokémon" and edit flows keep working without a login UI.
  const method = String(options.method || 'GET').toUpperCase();
  if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(method)) {
    try {
      const token = await getDemoToken(API_BASE_URL);
      headers.Authorization = `Bearer ${token}`;
    } catch (error) {
      // Fall through so the API can return its own clear 401 response.
    }
  }

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 5000);

    const response = await fetch(`${API_BASE_URL}${path}`, {
      ...restOptions,
      signal: controller.signal,
      headers,
    });
    clearTimeout(timeoutId);

    if (response.status === 503) {
      // Backend is deployed but its database is unavailable — use local seed data.
      return handleLocalFallback(path, options);
    }

    if (!response.ok) {
      const text = await response.text();
      throw new Error(text || `Request failed with status ${response.status}`);
    }

    if (response.status === 204) {
      return null;
    }

    return await response.json();
  } catch (error) {
    // Only fall back to local data for network/timeout failures.
    // Re-throw server errors so callers can surface them.
    const isNetworkError =
      error?.name === 'TypeError' ||
      error?.name === 'AbortError' ||
      /network/i.test(error?.message || '');
    if (!isNetworkError) {
      throw error;
    }
    // Return fallback local data when backend server is unreachable
    return handleLocalFallback(path, options);
  }
}

function handleLocalFallback(path, options) {
  const method = (options.method || 'GET').toUpperCase();
  // Strip any query string (e.g. /pokemon?userId=...) so the local fallback
  // matches the same routes as when the backend is online.
  const pathname = String(path).split('?')[0];

  if (pathname === '/pokemon' && method === 'GET') {
    return [...localPokemonPool];
  }

  if (pathname.startsWith('/pokemon/') && method === 'GET') {
    const id = pathname.replace('/pokemon/', '');
    const found = localPokemonPool.find((p) => String(p._id) === String(id));
    if (found) return { ...found };
    throw new Error('Pokémon not found');
  }

  if (pathname === '/pokemon' && method === 'POST') {
    const payload = JSON.parse(options.body || '{}');
    const newEntry = {
      _id: String(Date.now()),
      name: payload.name || 'New Pokémon',
      types: Array.isArray(payload.types) ? payload.types : ['Normal'],
      level: payload.level || 1,
      sprite: payload.sprite || 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/25.png',
    };
    localPokemonPool = [newEntry, ...localPokemonPool];
    return { ...newEntry };
  }

  if (pathname.startsWith('/pokemon/') && (method === 'PATCH' || method === 'PUT')) {
    const id = pathname.replace('/pokemon/', '');
    const payload = JSON.parse(options.body || '{}');
    localPokemonPool = localPokemonPool.map((item) => {
      if (String(item._id) === String(id)) {
        return { ...item, ...payload };
      }
      return item;
    });
    const updated = localPokemonPool.find((item) => String(item._id) === String(id));
    if (!updated) {
      throw new Error('Pokémon not found');
    }
    return { ...updated };
  }

  if (pathname.startsWith('/pokemon/') && method === 'DELETE') {
    const id = pathname.replace('/pokemon/', '');
    localPokemonPool = localPokemonPool.filter((item) => String(item._id) !== String(id));
    return null;
  }

  throw new Error(`Unsupported request: ${method} ${path}`);
}

export async function getPokemonList() {
  const userId = await getUserId();
  const query = userId ? `?userId=${encodeURIComponent(userId)}` : '';
  return requestJson(`/pokemon${query}`);
}

export function getPokemonById(id) {
  return requestJson(`/pokemon/${id}`);
}

export function createPokemon(payload) {
  return requestJson('/pokemon', {
    method: 'POST',
    body: JSON.stringify(payload),
  });
}

export function updatePokemon(id, payload) {
  return requestJson(`/pokemon/${id}`, {
    method: 'PATCH',
    body: JSON.stringify(payload),
  });
}

export function deletePokemon(id) {
  return requestJson(`/pokemon/${id}`, { method: 'DELETE' });
}


