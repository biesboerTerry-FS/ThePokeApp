import { writeFileSync } from 'node:fs';

// Generates src/api/backendStatus.generated.js at build time. When the backend
// is degraded (503 while MongoDB is being set up), the web app skips API calls
// entirely and uses the bundled offline data — no failed network requests in
// the browser. After MongoDB is connected, simply redeploy and the cloud path
// is enabled automatically.
const base = String(process.env.EXPO_PUBLIC_API_BASE_URL || 'http://localhost:8000/api/v1').replace(/\/+$/, '');
let healthy = false;

try {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 4000);
  const response = await fetch(`${base}/health`, { signal: controller.signal });
  clearTimeout(timeout);

  if (response.ok) {
    healthy = true;
  } else if (response.status === 503) {
    // Definitively degraded (database not connected) — stay local.
    healthy = false;
  } else {
    // Unknown response: let the runtime try and fall back if needed.
    healthy = true;
  }
} catch (error) {
  // No explicit API URL (or unreachable local backend): use the offline demo.
  healthy = Boolean(process.env.EXPO_PUBLIC_API_BASE_URL);
}

writeFileSync(
  new URL('../src/api/backendStatus.generated.js', import.meta.url),
  `// Generated by scripts/check-backend.mjs — do not edit by hand.\nexport const backendHealthyAtBuild = ${healthy};\n`
);

console.log(`Backend health probe: ${healthy ? 'healthy' : 'degraded (using local fallback)'}`);
